# 2. ГЕНЕРАЦИЯ ДАННЫХ ПО ВАРИАНТУ (распределение К - кластеризованное)
# ===========================================================================

def make_clustered_data(n, seed=SEED_DATA):
    """Строит упорядоченный массив из n ключей распределения К.

    КАК РАБОТАЕТ:
      - 90 % ключей (small штук) берём из узкого диапазона [0; n]:
        на диапазон длины n+1 приходится ~0.9n значений, поэтому они
        «толпятся» и ДАЮТ ПОВТОРЫ (это и есть кластеризация);
      - 10 % ключей (остальные) берём из широкого диапазона
        [10^6; 10^7] - почти без повторов;
      - сортируем список, потому что двоичному и интерполяционному поиску
        нужен упорядоченный массив.

    Замечание про seed: seed + n делает данные для разных n разными,
    но воспроизводимыми (при повторном запуске результат тот же).
    """
    rng = random.Random(seed + n)
    small = int(round(0.9 * n))          # сколько ключей в нижнем кластере
    keys = [rng.randint(0, n) for _ in range(small)]
    keys += [rng.randint(RANGE_BIG[0], RANGE_BIG[1]) for _ in range(n - small)]
    keys.sort()
    return keys


def make_successful_queries(data, k=K, seed=SEED_QUERY):
    """Готовит k УСПЕШНЫХ запросов (ключи точно есть в массиве).

    КАК РАБОТАЕТ:
      Берём случайный ИНДЕКС j внутри массива и возвращаем data[j].
      Такой ключ гарантированно присутствует (мы его только что взяли
      из массива), значит поиск всегда будет успешным - как требует вариант.
      Даже если в массиве есть повторы, data[j] - корректный ключ.
    """
    rng = random.Random(seed + len(data))
    return [data[rng.randrange(len(data))] for _ in range(k)]


