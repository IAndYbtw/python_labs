"""
Лабораторная работа № 4. Вариант 11.
Анализ последовательного, двоичного и интерполяционного поиска.

Исходные данные (вариант 11, табл. 2):
  - размеры массива n = 10^3, 10^4, 10^5;
  - распределение ключей К (кластеризованное):
        90 % ключей из диапазона [0; n]  (тесный кластер -> много повторов),
        10 % ключей из [10^6; 10^7]      (широкий, почти без повторов);
  - число запросов k = 500, все запросы успешные;
  - дополнительное задание Б4: поиск первого и последнего вхождения ключа
    за O(log n) и подсчёт числа вхождений.
"""
import math
import random
import time
from collections import Counter
from bisect import bisect_left, bisect_right   # эталон для проверки задания Б4

# ---------------------------------------------------------------------------
# Константы варианта 11
# ---------------------------------------------------------------------------
SIZES = [10**3, 10**4, 10**5]   # размеры исследуемых массивов
K = 500                          # число запросов в одной серии
SEED_DATA = 42                   # «зерно» для генерации массива (повторяемость)
SEED_QUERY = 1                   # «зерно» для генерации запросов
RANGE_BIG = (10**6, 10**7)       # верхний кластер распределения К


# ===========================================================================
# 1. АЛГОРИТМЫ ПОИСКА
#    Каждая функция возвращает ПАРУ: (индекс | -1, число сравнений).
#    Число сравнений нужно, чтобы потом сверить эксперимент с теорией.
# ===========================================================================

def linear_search(a, q):
    """Последовательный (линейный) поиск.

    КАК РАБОТАЕТ:
      Идём по массиву слева направо (enumerate выдаёт индекс i и элемент
      value). На каждом шаге делаем ОДНО сравнение `value == q`:
        - совпало -> ключ найден на позиции i; сравнений выполнено i + 1
          (мы просмотрели элементы с индексами 0..i);
        - не совпало -> идём дальше.
      Если дошли до конца и ничего не нашли, возвращаем -1.

    СЛОЖНОСТЬ:
      Успешный поиск в среднем (n+1)/2 сравнений, неуспешный - всегда n.
      Порядок элементов НЕ важен: массив может быть любым.
    """
    for i, value in enumerate(a):
        if value == q:            # одно сравнение на каждой позиции
            return i, i + 1       # позиция найдена; сравнений = i + 1
    return -1, len(a)             # не найден; сравнили все n элементов


def binary_search(a, q):
    """Двоичный (бинарный) поиск. Требует УПОРЯДОЧЕННОГО массива.

    КАК РАБОТАЕТ:
      Держим отрезок [lo; hi], внутри которого может находиться ключ.
      На каждом шаге смотрим на СЕРЕДИНУ mid = lo + (hi - lo) // 2:
        - a[mid] == q  -> нашли, возвращаем mid;
        - a[mid] <  q  -> всё, что левее mid, тоже меньше q, поэтому
                          сдвигаем левую границу: lo = mid + 1;
        - a[mid] >  q  -> всё, что правее mid, больше q, сдвигаем правую
                          границу: hi = mid - 1.
      Отрезок на каждом шаге уменьшается ВДВОЕ, цикл идёт, пока lo <= hi.

    ВАЖНЫЕ ДЕТАЛИ:
      - середину считаем как lo + (hi - lo) // 2, а не (lo + hi) // 2:
        при больших lo и hi сумма могла бы переполниться (в Python это
        не критично, но это «безопасная» форма);
      - применять можно ТОЛЬКО к отсортированному массиву, иначе результат
        неверный и без каких-либо сообщений об ошибке.9

    СЛОЖНОСТЬ:
      Худший случай ~ floor(log2 n) + 1 сравнений = Theta(log n).
    """
    lo, hi, cmps = 0, len(a) - 1, 0
    while lo <= hi:
        mid = lo + (hi - lo) // 2     # безопасная середина отрезка
        cmps += 1                     # считаем сравнение с ключом
        if a[mid] == q:
            return mid, cmps
        if a[mid] < q:                # ключ правее середины
            lo = mid + 1
        else:                         # ключ левее середины
            hi = mid - 1
    return -1, cmps                   # отрезок пуст -> ключа нет


def interpolation_search(a, q):
    """Интерполяционный поиск. Требует УПОРЯДОЧЕННОГО массива.

    КАК РАБОТАЕТ:
      Это «умный» двоичный поиск: вместо середины вычисляем ОЖИДАЕМУЮ
      позицию ключа, предполагая, что значения распределены РАВНОМЕРНО.
      Формула (линейная интерполяция между границами):
          mid = lo + (q - a[lo]) * (hi - lo) // (a[hi] - a[lo])
      Смысл: если q близко к a[lo], берём позицию около левого края;
      если q близко к a[hi] - около правого. Так человек ищет слово
      в словаре: букву «А» открываем в начале, а не в середине.

      Дальше логика та же, что у двоичного: сравнили a[mid] и q,
      сузили отрезок влево или вправо.

    ЗАЩИТА ОТ ОСОБЫХ СЛУЧАЕВ:
      - условие `a[lo] <= q <= a[hi]`: если ключ выходит за границы
        текущего отрезка, его в массиве нет -> сразу -1;
      - если a[lo] == a[hi] (все значения на отрезке одинаковы), делить
        на (a[hi] - a[lo]) = 0 нельзя, поэтому отдельно проверяем,
        равен ли этот единственный ключ искомому.

    СЛОЖНОСТЬ:
      На равномерных данных O(log log n); на неравномерных (как у нас,
      распределение К) деградирует вплоть до Theta(n). Это и покажет опыт.
    """
    lo, hi, cmps = 0, len(a) - 1, 0
    while lo <= hi and a[lo] <= q <= a[hi]:
        if a[lo] == a[hi]:            # все элементы отрезка одинаковы
            cmps += 1
            return (lo, cmps) if a[lo] == q else (-1, cmps)
        # ожидаемая позиция ключа при равномерном распределении
        mid = lo + (q - a[lo]) * (hi - lo) // (a[hi] - a[lo])
        cmps += 1
        if a[mid] == q:
            return mid, cmps
        if a[mid] < q:
            lo = mid + 1
        else:
            hi = mid - 1
    return -1, cmps


