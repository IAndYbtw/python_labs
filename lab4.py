# 5. ОСНОВНАЯ ПРОГРАММА
# ===========================================================================

def main():
    algorithms = {
        "Последовательный": linear_search,
        "Двоичный": binary_search,
        "Интерполяционный": interpolation_search,
    }

    print("=" * 78)
    print("ЛР № 4, вариант 11: распределение К, k = 500 успешных запросов")
    print("=" * 78)

    # Накопители для сводных таблиц (по одному значению на каждый n)
    time_rows = {name: [] for name in algorithms}
    cmps_rows = {name: [] for name in algorithms}
    theory = {name: [] for name in algorithms}

    # --- основной цикл по размерам массива ---
    for n in SIZES:
        data = make_clustered_data(n)           # массив по варианту
        queries = make_successful_queries(data)  # 500 успешных ключей
        repeats = len(data) - len(set(data))    # сколько в массиве повторов
        print(f"\nn = {n}  (повторов в массиве: {repeats})")
        print(f"{'Алгоритм':<18}{'время, мкс':>12}{'сравнений':>12}{'теория':>10}")

        for name, func in algorithms.items():
            t, c = benchmark(func, data, queries)   # замер времени и сравнений
            time_rows[name].append(t)
            cmps_rows[name].append(c)

            # теоретическая оценка числа сравнений для каждой точки
            if name == "Последовательный":
                th = (n + 1) / 2               # среднее при успешном поиске
            elif name == "Двоичный":
                th = math.log2(n)              # худший случай
            else:
                th = math.log2(math.log2(n))   # при равномерных данных
            theory[name].append(th)

            print(f"{name:<18}{t * 1e6:>12.2f}{c:>12.2f}{th:>10.2f}")

    # --- сводная таблица: среднее время одного запроса, мкс ---
    print("\nТаблица. Среднее время одного запроса, мкс")
    print(f"{'n':>8}" + "".join(f"{name:>18}" for name in algorithms))
    for i, n in enumerate(SIZES):
        row = f"{n:>8}"
        for name in algorithms:
            row += f"{time_rows[name][i] * 1e6:>18.2f}"
        print(row)

    # --- сводная таблица: среднее число сравнений на запрос ---
    print("\nТаблица. Среднее число сравнений на один запрос")
    print(f"{'n':>8}" + "".join(f"{name:>16}" for name in algorithms))
    for i, n in enumerate(SIZES):
        row = f"{n:>8}"
        for name in algorithms:
            row += f"{cmps_rows[name][i]:>16.2f}"
        print(row)

    # --- дополнительное задание Б4 ---
    print("\n" + "=" * 78)
    print("Дополнительное задание Б4: границы диапазона и число вхождений")
    print("=" * 78)

    n = 10**4
    data = make_clustered_data(n)
    # берём самый частый ключ - у него гарантированно есть повторы
    most_common = Counter(data).most_common(1)[0][0]
    absent = max(data) + 5            # ключ, которого точно нет в массиве

    print(f"Проверка на массиве n = {n}, повторов: {len(data) - len(set(data))}")
    print(f"{'ключ':>12}{'первое':>8}{'последнее':>10}{'число':>7}"
          f"{'bisect':>9}{'naive':>8}")
    for q in [most_common, data[0], data[-1], absent]:
        first, _ = first_occurrence(data, q)
        last, _ = last_occurrence(data, q)
        cnt, cmps = count_occurrences(data, q)
        ref = bisect_right(data, q) - bisect_left(data, q)  # эталон (bisect)
        naive = data.count(q)                               # эталон (наивно)
        print(f"{q:>12}{first:>8}{last:>10}{cnt:>7}{ref:>9}{naive:>8}"
              f"   (сравнений для подсчёта: {cmps})")


if __name__ == "__main__":
    main()
