# 3. ЗАМЕР ВРЕМЕНИ И ЧИСЛА СРАВНЕНИЙ
# ===========================================================================

def benchmark(search_func, data, queries, repeats=5):
    """Возвращает среднее время одного запроса (с) и среднее число сравнений.

    КАК РАБОТАЕТ:
      Отдельный запрос слишком быстр, чтобы измерить его напрямую, поэтому
      измеряем СЕРИЮ из k запросов целиком и делим на их число.

      - повторяем серию `repeats` раз и берём МЕДИАНУ времени, чтобы
        случайные «всплески» ОС не исказили результат;
      - число сравнений накапливаем по всем повторам и всем запросам,
        затем делим на общее число запросов (repeats * len(queries)).

      Итог: (время_серии / k, сумма_сравнений / (repeats * k)).
    """
    times = []
    total_cmps = 0
    for _ in range(repeats):
        start = time.perf_counter()
        for q in queries:
            _, cmps = search_func(data, q)   # индекс не нужен, только cmps
            total_cmps += cmps
        times.append(time.perf_counter() - start)
    med = sorted(times)[len(times) // 2]     # медиана по repeats повторениям
    return med / len(queries), total_cmps / (repeats * len(queries))


# ===========================================================================
# 4. ДОПОЛНИТЕЛЬНОЕ ЗАДАНИЕ Б4:
#    поиск границ диапазона (первое/последнее вхождение) и число вхождений
# ===========================================================================

def lower_bound(a, q):
    """Индекс ПЕРВОГО элемента >= q (аналог bisect_left). O(log n).

    КАК РАБОТАЕТ:
      Это вариация двоичного поиска с «открытым» правым концом hi = n.
      Инвариант: все элементы левее lo строго < q, все элементы от hi
      и правее - >= q. Пока lo < hi:
        - если a[mid] < q, то mid и всё левее нам не подходят -> lo = mid+1;
        - иначе a[mid] >= q, сдвигаем hi = mid (не mid-1, т.к. a[mid]
          может оказаться первым подходящим).
      Когда lo == hi, это и есть позиция первого элемента >= q.
    """
    lo, hi, cmps = 0, len(a), 0
    while lo < hi:
        mid = lo + (hi - lo) // 2
        cmps += 1
        if a[mid] < q:
            lo = mid + 1
        else:
            hi = mid
    return lo, cmps


def upper_bound(a, q):
    """Индекс ПЕРВОГО элемента > q (аналог bisect_right). O(log n).

    КАК РАБОТАЕТ:
      То же самое, но сдвигаем левую границу при a[mid] <= q:
        - если a[mid] <= q, то всё до mid включительно не больше q,
          сдвигаем lo = mid + 1;
        - иначе a[mid] > q, сдвигаем hi = mid.
      Результат - позиция первого элемента строго больше q, т.е.
      последний входящий в диапазон элемент имеет индекс upper_bound - 1.
    """
    lo, hi, cmps = 0, len(a), 0
    while lo < hi:
        mid = lo + (hi - lo) // 2
        cmps += 1
        if a[mid] <= q:
            lo = mid + 1
        else:
            hi = mid
    return lo, cmps


def first_occurrence(a, q):
    """Первое вхождение q, либо -1, если ключа нет."""
    lo, cmps = lower_bound(a, q)
    # lower_bound даёт первый >= q; если там не сам q, значит q отсутствует
    return (lo, cmps) if (lo < len(a) and a[lo] == q) else (-1, cmps)


def last_occurrence(a, q):
    """Последнее вхождение q, либо -1, если ключа нет."""
    up, cmps = upper_bound(a, q)
    # upper_bound даёт первый > q; предыдущий элемент - последний == q
    return (up - 1, cmps) if (up > 0 and a[up - 1] == q) else (-1, cmps)


def count_occurrences(a, q):
    """Число вхождений q (0, если ключа нет). O(log n).

    КАК РАБОТАЕТ:
      Сначала lower_bound находит первый элемент >= q. Если его нет или он
      не равен q, ключ отсутствует -> возвращаем 0. Иначе upper_bound
      находит первый элемент > q, и число вхождений равно разности
      upper_bound - lower_bound (все элементы между ними равны q, т.к.
      массив отсортирован).
    """
    lo, c1 = lower_bound(a, q)
    if lo == len(a) or a[lo] != q:
        return 0, c1
    up, c2 = upper_bound(a, q)
    return up - lo, c1 + c2


