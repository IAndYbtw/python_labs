"""
Лабораторная работа № 7. Вариант 11.
Рекурсивные алгоритмы и динамическое программирование.

Исходные данные (вариант 11, табл. 1):
  - Задача А:  числа Фибоначчи, параметр n = 10..31, три реализации
               (наивная рекурсия, мемоизация, итеративная) со счётчиком вызовов;
  - Задача Б:  размен суммы S = 250 монетами номиналов 1, 4, 6, 9
               методом динамического программирования с восстановлением решения;
  - Доп. задание Г4: зависимость времени ДП от S при фиксированных номиналах,
               подтверждение линейности и пояснение псевдополиномиальности.
"""
import time
from collections import Counter
from itertools import combinations_with_replacement

# ===========================================================================
# 1. ЗАДАЧА А: ЧИСЛА ФИБОНАЧЧИ (три реализации)
#    F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2)
# ===========================================================================

calls = 0          # глобальный счётчик вызовов (обнуляется перед каждым замером)


def fib_naive(n):
    """Наивная рекурсия — Theta(phi^n).

    КАК РАБОТАЕТ: вычисляет F(n-1) и F(n-2) заново на каждом шаге. Одна и та
    же подзадача решается многократно, поэтому число вызовов растёт
    экспоненциально (примерно в phi = 1.618 раза при увеличении n на 1).
    """
    global calls
    calls += 1
    if n < 2:
        return n
    return fib_naive(n - 1) + fib_naive(n - 2)


def fib_memo(n, cache=None):
    """Нисходящее ДП (мемоизация) — Theta(n).

    КАК РАБОТАЕТ: та же рекурсия, но результат каждого n сохраняется в
    словаре cache. Если значение уже посчитано, оно берётся из кэша, и
    ветка F(n-2) больше не вычисляется повторно. Каждая подзадача решается
    ровно один раз -> число вызовов около 2n-1.
    """
    global calls
    calls += 1
    if cache is None:
        cache = {}
    if n < 2:
        return n
    if n in cache:
        return cache[n]
    cache[n] = fib_memo(n - 1, cache) + fib_memo(n - 2, cache)
    return cache[n]


def fib_iter(n):
    """Восходящее ДП (итеративно) — Theta(n) времени, O(1) памяти.

    КАК РАБОТАЕТ: храним только два последних числа (a, b) и на каждом шаге
    сдвигаем их. Рекурсии нет вовсе, поэтому нет ни накладных расходов на
    вызовы, ни ограничения глубины стека.
    """
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


# ===========================================================================
# 2. ЗАДАЧА Б: РАЗМЕН СУММЫ МИНИМАЛЬНЫМ ЧИСЛОМ МОНЕТ (ДП)
#    D[s] = 1 + min_{c <= s} D[s - c],  D[0] = 0
# ===========================================================================

def coin_change_dp(coins, S, recover=True):
    """Минимальное число монет для суммы S. Возвращает (число, список монет).

    КАК РАБОТАЕТ (восходящее ДП):
      D[s] — минимальное число монет, дающих в сумме s.
      База: D[0] = 0 (для суммы 0 монеты не нужны).
      Переход: чтобы набрать s, берём последнюю монету c и добавляем её к
      оптимальному решению для s - c. Перебираем все номиналы и берём минимум.
      Сложность — Theta(k * S), где k — число номиналов.

      ВОССТАНОВЛЕНИЕ РЕШЕНИЯ: идём от S вниз и для текущей суммы s ищем
      номинал c, для которого D[s] == D[s - c] + 1. Это значит, что монета c
      входит в оптимальное решение; добавляем её и переходим к s - c.
    """
    INF = 10**9
    D = [INF] * (S + 1)
    D[0] = 0
    for s in range(1, S + 1):
        best = INF
        for c in coins:
            if c <= s and D[s - c] + 1 < best:
                best = D[s - c] + 1
        D[s] = best

    if not recover:            # для задания Г4 замеряем только заполнение
        return D[S]

    if D[S] >= INF:
        return None, []

    seq, s = [], S
    while s > 0:               # обратный проход по таблице D
        for c in coins:
            if c <= s and D[s] == D[s - c] + 1:
                seq.append(c)
                s -= c
                break
    return D[S], seq


def coin_change_brute(coins, s):
    """Полный перебор (для проверки ДП на малых суммах).

    КАК РАБОТАЕТ: перебираем число монет k = 1, 2, 3, ... и для каждого k
    просматриваем ВСЕ сочетания с повторениями из k номиналов. Первое
    сочетание, дающее сумму s, и есть ответ (по построению k минимально).
    Это экспоненциально по s, поэтому годится только для малых значений.
    """
    for k in range(1, s + 1):
        for combo in combinations_with_replacement(coins, k):
            if sum(combo) == s:
                return k, list(combo)
    return None, []


