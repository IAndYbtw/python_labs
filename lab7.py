# 3. ОСНОВНАЯ ПРОГРАММА
# ===========================================================================

def main():
    print("=" * 78)
    print("ЛР № 7, вариант 11: Фибоначчи (3 реализации) + размен суммы (ДП)")
    print("=" * 78)

    # --- 3.1. Дерево рекурсии: повторяющиеся подзадачи для F(5) ---
    print("\n--- Повторяющиеся подзадачи: сколько раз вызывается F(k) при F(5) ---")
    cnt = {}

    def fib_count(n):
        cnt[n] = cnt.get(n, 0) + 1
        if n < 2:
            return n
        return fib_count(n - 1) + fib_count(n - 2)

    fib_count(5)
    print("  " + ", ".join(f"F({k}) x{v}" for k, v in sorted(cnt.items(), reverse=True)))
    print("  Видно, что F(3) считается дважды, F(2) — трижды, F(1) — пять раз.")

    # --- 3.2. Задача А: сравнение трёх реализаций ---
    print("\n--- Задача А: числа Фибоначчи ---")
    print(f"{'n':>4} {'наивная, с':>12} {'вызовов':>12} {'мемо, с':>11}"
          f"{'вызовов':>9} {'итер., с':>10} {'F(n)':>12}")
    for n in [10, 15, 20, 25, 30, 31]:
        global calls
        calls = 0
        t0 = time.perf_counter(); r1 = fib_naive(n); t_naive = time.perf_counter() - t0
        c_naive = calls

        calls = 0
        t0 = time.perf_counter(); r2 = fib_memo(n); t_memo = time.perf_counter() - t0
        c_memo = calls

        t0 = time.perf_counter(); r3 = fib_iter(n); t_iter = time.perf_counter() - t0
        assert r1 == r2 == r3, "три реализации дали разные результаты!"
        print(f"{n:>4} {t_naive:>12.4f} {c_naive:>12,} {t_memo:>11.6f}"
              f"{c_memo:>9,} {t_iter:>10.6f} {r1:>12,}")

    # --- 3.3. Предел наивной рекурсии (ориентир 10 с) ---
    print("\n--- Предел наивной рекурсии (ориентир 10 с) ---")
    for n in [34, 36, 38, 39, 40, 41]:
        calls = 0
        t0 = time.perf_counter()
        fib_naive(n)
        dt = time.perf_counter() - t0
        print(f"  n = {n:>2}: {dt:>7.2f} с, вызовов {calls:>12,}")
        if dt > 10:
            print(f"  => наивная рекурсия перестаёт укладываться в 10 с "
                  f"примерно при n = {n}")
            break

    # --- 3.4. Задача Б: размен суммы ---
    print("\n--- Задача Б: размен суммы S = 250 монетами 1, 4, 6, 9 ---")
    coins = [1, 4, 6, 9]
    S = 250
    t0 = time.perf_counter()
    count_dp, seq = coin_change_dp(coins, S)
    t_dp = time.perf_counter() - t0
    freq = Counter(seq)
    print(f"  минимальное число монет: {count_dp}")
    print(f"  состав: {dict(sorted(freq.items()))}")
    print(f"  проверка суммы: {sum(seq)} = {S}")
    print(f"  время ДП: {t_dp:.6f} с")

    # --- 3.5. Сверка ДП с полным перебором (малые суммы) ---
    print("\n--- Сверка ДП с полным перебором (малые суммы) ---")
    print(f"{'S':>4} {'ДП':>6} {'перебор':>8} {'совпало':>8}")
    for s in [10, 15, 20, 25, 30]:
        c_dp, _ = coin_change_dp(coins, s)
        c_bf, _ = coin_change_brute(coins, s)
        print(f"{s:>4} {c_dp:>6} {c_bf:>8} {str(c_dp == c_bf):>8}")

    # --- 3.6. Доп. задание Г4: время ДП в зависимости от S ---
    print("\n--- Г4: время ДП размена в зависимости от суммы S ---")
    print(f"{'S':>9} {'время, с':>12}")
    prev = None
    for s in [50_000, 100_000, 200_000, 400_000]:
        times = []
        for _ in range(3):
            t0 = time.perf_counter()
            coin_change_dp(coins, s, recover=False)
            times.append(time.perf_counter() - t0)
        t = sorted(times)[1]               # медиана из 3
        ratio = f"  T(2S)/T(S) = {t / prev:.2f}" if prev else ""
        print(f"{s:>9} {t:>12.6f}{ratio}")
        prev = t
    print("  Время растёт линейно по S (T(2S)/T(S) ~ 2) при фиксированных")
    print("  номиналах, что подтверждает оценку Theta(k*S).")


if __name__ == "__main__":
    main()
