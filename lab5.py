def main():
    alpha = N / M
    print("=" * 78)
    print("ЛР № 5, вариант 11: метод деления; квадратичное пробирование и")
    print("двойное хеширование")
    print(f"n = {N}, m = {M}, alpha = {alpha:.4f}")
    print("=" * 78)

    # --- ключи и запросы (воспроизводимо благодаря фиксированным зернам) ---
    rng = random.Random(42)
    keys = rng.sample(range(10_000_000), N)        # 40 000 различных ключей
    success_queries = [rng.choice(keys) for _ in range(QUERY_K)]
    # неуспешные ключи берём из ДИЗЪЮНКТНОГО диапазона — их точно нет в таблице
    fail_queries = rng.sample(range(10_000_000, 20_000_000), QUERY_K)

    # --- основной эксперимент ---
    print(f"\n{'Метод':<24}{'вставка, с':>12}{'поиск, с':>12}"
          f"{'проб/усп.':>10}{'проб/неусп.':>13}{'макс. проб':>11}{'макс. кластер':>14}")
    for probing, name in [("quadratic", "Квадратичное"),
                          ("double", "Двойное хеширование")]:
        ti, ts, ps, pf, table = run_experiment(
            probing, keys, success_queries, fail_queries)
        print(f"{name:<24}{ti:>12.3f}{ts:>12.3f}{ps:>10.2f}{pf:>13.2f}"
              f"{table.max_insert_probes:>11}{table.max_run():>14}")

    # --- эталон: встроенный словарь ---
    t0 = time.perf_counter()
    d = {k: k for k in keys}
    ti = time.perf_counter() - t0
    t0 = time.perf_counter()
    for q in success_queries:
        d.get(q)
    ts = time.perf_counter() - t0
    print(f"{'dict (эталон)':<24}{ti:>12.3f}{ts:>12.3f}")

    # --- сравнение хорошей и плохой хеш-функций ---
    print("\n" + "-" * 78)
    print("Хорошая vs плохая хеш-функция (40 000 ключей):")
    dist_report("k mod 65521 (хорошая)", M, keys)
    dist_report("k mod 10    (плохая)", 10, keys)

    # --- дополнительное задание В4 ---
    print("\n" + "=" * 78)
    print("Доп. задание В4: число проб при неуспешном поиске vs alpha")
    print("=" * 78)
    print(f"{'alpha':>8}{'квадр.':>12}{'двойн.':>12}{'теория 1/(1-a)':>17}")
    for a in (0.1, 0.3, 0.5, 0.7, 0.9, 0.95):
        n = int(a * M)                             # сколько ключей вставить
        keys_a = random.Random(1000 + int(a * 100)).sample(
            range(30_000_000, 40_000_000), n)      # отдельный диапазон ключей
        fails = random.Random(2000 + int(a * 100)).sample(
            range(40_000_000, 50_000_000), QUERY_K)
        row = f"{a:>8.2f}"
        for probing in ("quadratic", "double"):
            table = OpenAddressingTable(M, probing=probing)
            for k in keys_a:
                table.insert(k, k)
            table.probes = 0
            for q in fails:
                table.search(q)
            row += f"{table.probes / len(fails):>12.2f}"
        row += f"{1 / (1 - a):>17.2f}"
        print(row)


if __name__ == "__main__":
    main()
