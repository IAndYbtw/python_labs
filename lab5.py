# 2. ЗАМЕР ВРЕМЕНИ И ЧИСЛА ПРОБ
# ===========================================================================

def run_experiment(probing, keys, success_queries, fail_queries):
    """Заполняет таблицу, измеряет время вставки/поиска и среднее число проб.

    КАК РАБОТАЕТ:
      1) создаём таблицу нужного типа (probing);
      2) засекаем время и вставляем все ключи;
      3) обнуляем счётчик проб, засекаем время и ищем все УСПЕШНЫЕ ключи
         (они гарантированно есть в таблице) -> получаем среднее число проб
         на успешный поиск;
      4) снова обнуляем счётчик, ищем все НЕУСПЕШНЫЕ ключи (их точно нет)
         -> среднее число проб на неуспешный поиск (нужно для задания В4,
         где теория даёт 1/(1-alpha)).

      Возвращает кортеж: (время вставки, время поиска, проб/успешный,
                          проб/неуспешный).
    """
    table = OpenAddressingTable(M, probing=probing)

    t0 = time.perf_counter()
    for k in keys:
        table.insert(k, k)
    t_insert = time.perf_counter() - t0

    table.probes = 0
    t0 = time.perf_counter()
    for q in success_queries:
        table.search(q)
    t_search = time.perf_counter() - t0
    probes_success = table.probes / len(success_queries)

    table.probes = 0
    t0 = time.perf_counter()
    for q in fail_queries:
        table.search(q)
    _ = time.perf_counter() - t0
    probes_fail = table.probes / len(fail_queries)

    return t_insert, t_search, probes_success, probes_fail, table


