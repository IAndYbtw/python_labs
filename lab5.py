"""
Лабораторная работа № 5. Вариант 11.
Хеширование и экспериментальное исследование методов разрешения коллизий.

Исходные данные (вариант 11, табл. 1):
  - тип ключей:      целые случайные числа;
  - хеш-функция:     Д — метод деления h(k) = k mod m, m = 65 521 (простое);
  - разрешение коллизий: К — квадратичное пробирование,
                         Дв — двойное хеширование;
  - число элементов n = 40 000, размер таблицы m = 65 521;
  - дополнительное задание В4: зависимость числа проб от коэффициента

"""
import math
import random
import time

M = 65_521          # размер таблицы (простое число -> метод деления работает хорошо)
N = 40_000          # число вставляемых ключей (вариант 11)
QUERY_K = 10_000    # число запросов в замерной серии


# ===========================================================================
# 1. ХЕШ-ТАБЛИЦА С ОТКРЫТОЙ АДРЕСАЦИЕЙ
#    Одна реализация с двумя стратегиями пробирования: квадратичное и двойное.
# ===========================================================================

class OpenAddressingTable:
    """Хеш-таблица с открытой адресацией.

    КАК УСТРОЕНА:
      Все элементы лежат прямо в массивах self.keys / self.values, никаких
      списков-цепочек нет. Если нужная ячейка занята, ищем следующую по
      правилу пробирования (квадратично или двойным хешированием).

    ОБОЗНАЧЕНИЯ:
      - self.EMPTY — маркер «ячейка пуста» (уникальный объект, чтобы его
        нельзя было спутать с реальным ключом);
      - self.n     — сколько ключей сейчас хранится;
      - self.probes — суммарный счётчик проб; перед замером поиска его
        обнуляют, после серии запросов делят на их число.
    """

    EMPTY = object()          # маркер пустой ячейки

    def __init__(self, m, probing="double"):
        self.m = m                          # размер таблицы
        self.probing = probing              # "quadratic" или "double"
        self.keys = [self.EMPTY] * m        # массив ключей (EMPTY = пусто)
        self.values = [None] * m            # массив значений
        self.n = 0                          # текущее число ключей
        self.probes = 0                     # счётчик проб (для замера)
        self.max_insert_probes = 0          # худший случай вставки (диагностика)

    # --- хеш-функции ---
    def _h1(self, key):
        """Основной хеш (метод деления).

        КАК РАБОТАЕТ: берём остаток key % m. Почему m = 65 521 простое?
        Тогда в результат вовлекаются ВСЕ разряды ключа и значения
        распределяются по ячейкам равномерно. Если бы m было степенью
        двойки (например 65 536), key % m зависел бы только от МЛАДШИХ
        битов ключа — это давало бы много лишних коллизий.
        """
        return key % self.m

    def _h2(self, key):
        """Вторая хеш-функция — только для ДВОЙНОГО хеширования.

        КАК РАБОТАЕТ: должна возвращать значение из [1; m-1] и быть
        взаимно простой с m, чтобы последовательность проб
            (h1 + i * h2) mod m   при i = 0,1,2,...
        прошла ВСЕ m ячеек ровно по одному разу. Так как m = 65 521 простое,
        любое число от 1 до m-1 взаимно просто с m, поэтому формула
        1 + (key % (m-1)) гарантированно даёт подходящий шаг.
        """
        return 1 + (key % (self.m - 1))

    def _position(self, key, i):
        """Позиция i-й пробы для ключа key (i = 0 — первая попытка).

        КВАДРАТИЧНОЕ пробирование: pos = (h1 + i^2) mod m.
          Шаг растёт квадратично (1, 4, 9, ...), что уменьшает образование
          длинных сплошных участков (первичную кластеризацию) по сравнению
          с линейным пробированием (шаг всегда 1).

        ДВОЙНОЕ хеширование: pos = (h1 + i * h2) mod m.
          Шаг для каждого ключа СВОЙ (зависит от h2(key)), поэтому разные
          ключи идут по разным последовательностям — распределение проб
          наилучшее.
        """
        if self.probing == "quadratic":
            return (self._h1(key) + i * i) % self.m
        return (self._h1(key) + i * self._h2(key)) % self.m

    # --- операции ---
    def insert(self, key, value):
        """Вставка ключа (или обновление значения, если ключ уже есть).

        КАК РАБОТАЕТ:
          Пробуем ячейки i = 0, 1, 2, ... по правилу пробирования:
            - нашли ПУСТУЮ ячейку -> кладём туда (key, value), n += 1;
            - встретили ТОТ ЖЕ ключ -> обновляем его значение и выходим;
            - ячейка занята другим ключом -> продолжаем пробировать.
          Каждая просмотренная ячейка считается одной «пробой».
        """
        p = 0
        for i in range(self.m):
            p += 1
            pos = self._position(key, i)
            k = self.keys[pos]
            if k is self.EMPTY:
                self.keys[pos] = key
                self.values[pos] = value
                self.n += 1
                self.probes += p
                self.max_insert_probes = max(self.max_insert_probes, p)
                return
            if k == key:
                self.values[pos] = value      # ключ уже был — просто обновляем
                self.probes += p
                return
        raise RuntimeError("таблица переполнена")

    def search(self, key):
        """Поиск ключа. Возвращает значение либо None, если ключа нет.

        КАК РАБОТАЕТ:
          Идём по той же последовательности проб, что и при вставке:
            - дошли до ПУСТОЙ ячейки -> ключа точно нет (если бы он был,
              вставка положила бы его не дальше этой точки) — возвращаем None;
            - нашли сам ключ -> возвращаем его значение;
            - иначе продолжаем пробировать.
        """
        for i in range(self.m):
            self.probes += 1
            pos = self._position(key, i)
            k = self.keys[pos]
            if k is self.EMPTY:
                return None
            if k == key:
                return self.values[pos]
        return None

    def max_run(self):
        """Длина самого длинного НЕПРЕРЫВНОГО занятого участка (кластер).

        КАК РАБОТАЕТ: идём по массиву ячеек и считаем подряд идущие
        занятые ячейки. Чем длиннее такие участки, тем сильнее
        кластеризация и тем больше проб требуется при поиске.
        """
        best = cur = 0
        for k in self.keys:
            if k is not self.EMPTY:
                cur += 1
                best = max(best, cur)
            else:
                cur = 0
        return best


