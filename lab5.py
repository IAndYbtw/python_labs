# 3. СРАВНЕНИЕ ХОРОШЕЙ И ПЛОХОЙ ХЕШ-ФУНКЦИЙ
# ===========================================================================

def bucket_sizes(hash_func, m, keys):
    """Считает, сколько ключей попадает в каждую ячейку.

    КАК РАБОТАЕТ: для каждого ключа вычисляем hash_func(key) и увеличиваем
    счётчик соответствующей ячейки. Возвращает список размеров ячеек.
    По нему видно, насколько равномерно хеш распределяет ключи.
    """
    sizes = [0] * m
    for k in keys:
        sizes[hash_func(k)] += 1
    return sizes


def dist_report(name, m, keys):
    """Печатает сводку по распределению ключей по ячейкам."""
    sizes = bucket_sizes(lambda k: k % m, m, keys)
    non_empty = [s for s in sizes if s > 0]
    mean = sum(non_empty) / len(non_empty) if non_empty else 0
    variance = sum((s - mean) ** 2 for s in non_empty) / len(non_empty)
    print(f"{name:<24} ячеек {m:>6}  макс {max(sizes):>5}  "
          f"пустых {sizes.count(0):>6}  ст.откл {variance ** 0.5:>6.2f}")


